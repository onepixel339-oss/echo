const DICTS: Record<Language, Dict> = { en: EN, ar: AR };

/**
 * Standalone translator for a SPECIFIC language (independent of the active
 * interface language). Used by the taste card, which can render its shared
 * image in the other language than the app UI.
 */
export function translateFor(
  lang: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  let lookupKey = key;
  if (params && params.n === 1) {
    const one = `${key}_one`;
    if (DICTS[lang][one] ?? DICTS.en[one]) lookupKey = one;
  }
  let str = DICTS[lang][lookupKey] ?? DICTS.en[lookupKey] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

type TParams = Record<string, string | number>;

interface I18nContextValue {
  lang: Language;
  dir: "ltr" | "rtl";
  setLang: (lang: Language) => void;
  t: (key: string, params?: TParams) => string;
  /** translate a vocabulary slug (genre/tag) */
  tv: (slug: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({
  lang,
  onLangChange,
  children,
}: {
  lang: Language;
  onLangChange?: (lang: Language) => void;
  children: React.ReactNode;
}) {
  const t = useCallback(
    (key: string, params?: TParams) => {
      // singular form for n === 1 when a *_one variant exists
      let lookupKey = key;
      if (params && params.n === 1) {
        const one = `${key}_one`;
        if (DICTS[lang][one] ?? DICTS.en[one]) lookupKey = one;
      }
      let str = DICTS[lang][lookupKey] ?? DICTS.en[lookupKey] ?? key;
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          str = str.replaceAll(`{${k}}`, String(v));
        }
      }
      return str;
    },
    [lang],
  );
  const tv = useCallback((slug: string) => vocabLabel(slug, lang), [lang]);
  const setLang = useCallback(
    (l: Language) => onLangChange?.(l),
    [onLangChange],
  );

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const value = useMemo<I18nContextValue>(
    () => ({ lang, dir: lang === "ar" ? "rtl" : "ltr", setLang, t, tv }),
    [lang, setLang, t, tv],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
